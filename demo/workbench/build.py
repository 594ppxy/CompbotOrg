#!/usr/bin/env python3
"""Build the single-file CompBotOrg workbench.

head.html         : DSH design-system CSS (extracted once from the reference build)
app.css           : the workbench view layer
body.html         : shell markup, with a /*__APP_JS__*/ placeholder
ds-characters.js  : DSHBot's character table, generated by scripts/sync-characters.mjs
app.js            : state-driven UI
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SRC = ROOT / 'src'

head = (SRC / 'head.html').read_text()
css = (SRC / 'app.css').read_text()
body = (SRC / 'body.html').read_text()
chars = (SRC / 'ds-characters.js').read_text()
js = (SRC / 'app.js').read_text()

if '</head>' not in head:
    raise SystemExit('head.html is missing </head>')
head = head.replace(
    '</head>',
    '<style id="cb-app-css">\n' + css + '\n</style>\n</head>',
    1,
)

if '/*__APP_JS__*/' not in body:
    raise SystemExit('body.html is missing the /*__APP_JS__*/ placeholder')
# The character table is a separate global so app.js can stay readable; it has to be
# defined before app.js runs, which inlining here guarantees.
body = body.replace('/*__APP_JS__*/', '\n' + chars + '\n' + js + '\n', 1)

out = head + body
(ROOT / 'index.html').write_text(out)
print('built index.html: %d bytes (css %d, js %d, chars %d)' % (len(out), len(css), len(js), len(chars)))
